// Every event the app creates carries this text in its description. It lets
// cleanup find the app's events even when a task's stored event id is missing.
const AGENT_MARKER = "Generated by AI Task Agent";

const {getNZDayStart} = require("./time");

// Delete one event (best effort; never throws).
async function deleteCalendarEvent(calendar, calendarId, eventId) {
  if (!eventId) return;
  try {
    await calendar.events.delete({calendarId, eventId});
  } catch (err) {
    const status = err.status || err.code;
    // 404/410: event was already removed from Google Calendar
    if (status !== 404 && status !== 410) {
      console.warn(`Could not delete calendar event ${eventId}:`, err.message);
    }
  }
}

// Page through events.list and return every event for the given query options.
async function listEvents(calendar, calendarId, options) {
  const events = [];
  let pageToken;
  do {
    const res = await calendar.events.list({
      calendarId,
      maxResults: 250,
      showDeleted: false,
      pageToken,
      ...options,
    });
    events.push(...(res.data.items || []));
    pageToken = res.data.nextPageToken;
  } while (pageToken);
  return events;
}

// Event ids for the given query options, optionally narrowed by a filter on the event.
async function listEventIds(calendar, calendarId, options, filter) {
  const events = await listEvents(calendar, calendarId, options);
  return events.filter((ev) => ev.id && (!filter || filter(ev))).map((ev) => ev.id);
}

// Delete every calendar event belonging to a task: the stored event id plus any
// event tagged with the task's id. Best effort; never throws.
async function deleteTaskEvents(calendar, calendarId, task) {
  if (!task) return;
  const ids = new Set();
  if (task.googleCalendarEventId) ids.add(task.googleCalendarEventId);
  if (task.id) {
    try {
      const found = await listEventIds(calendar, calendarId, {privateExtendedProperty: `taskId=${task.id}`});
      found.forEach((id) => ids.add(id));
    } catch (err) {
      console.warn(`Could not look up calendar events for task ${task.id}:`, err.message);
    }
  }
  for (const id of ids) {
    await deleteCalendarEvent(calendar, calendarId, id);
  }
}

// Ids of every app-created event starting at or after timeMin (ISO string),
// including orphans whose tasks no longer exist. Throws if the lookup fails.
async function findAgentEventIds(calendar, calendarId, timeMin) {
  return listEventIds(
      calendar, calendarId,
      {timeMin, q: AGENT_MARKER, singleEvents: true},
      (ev) => (ev.description || "").includes(AGENT_MARKER),
  );
}

// Read-only: busy windows ({start, end}) for one calendar. Throws if the API call
// fails or Google reports an error for the calendar, so callers never schedule blind.
async function getBusyWindows(calendar, calendarId, timeMin, timeMax, timeZone) {
  const res = await calendar.freebusy.query({
    requestBody: {timeMin, timeMax, timeZone, items: [{id: calendarId}]},
  });
  const entries = (res.data && res.data.calendars) || {};
  const entry = entries[calendarId] || (Object.keys(entries).length === 1 ? Object.values(entries)[0] : undefined);
  if (!entry) throw new Error(`Free/busy response had no data for calendar ${calendarId}`);
  if (entry.errors && entry.errors.length) {
    throw new Error(`Free/busy failed for calendar ${calendarId}: ${entry.errors.map((e) => e.reason).join(", ")}`);
  }
  return entry.busy || [];
}

// Busy windows ({start, end}) from events that were not created by the app: opaque,
// not cancelled, not carrying the marker and not in excludeIds (a Set of event ids).
// Used for the agent calendar so the app's own previous events don't block rescheduling.
// Throws if the API call fails.
async function getForeignBusyWindows(calendar, calendarId, timeMin, timeMax, excludeIds = new Set()) {
  const events = await listEvents(calendar, calendarId, {timeMin, timeMax, singleEvents: true});
  const windows = [];
  for (const ev of events) {
    if (ev.status === "cancelled" || ev.transparency === "transparent") continue;
    if (excludeIds.has(ev.id) || (ev.description || "").includes(AGENT_MARKER)) continue;
    if (ev.start && ev.start.dateTime && ev.end && ev.end.dateTime) {
      windows.push({start: ev.start.dateTime, end: ev.end.dateTime});
    } else if (ev.start && ev.start.date && ev.end && ev.end.date) {
      windows.push({start: getNZDayStart(ev.start.date).toISOString(), end: getNZDayStart(ev.end.date).toISOString()});
    }
  }
  return windows;
}

// Sort busy windows and merge any that overlap or touch. Keeps the original
// start/end strings of the windows that bound each merged block.
function mergeBusyWindows(windows) {
  const parsed = windows
      .map((w) => ({start: w.start, end: w.end, startMs: Date.parse(w.start), endMs: Date.parse(w.end)}))
      .filter((w) => !Number.isNaN(w.startMs) && !Number.isNaN(w.endMs) && w.endMs > w.startMs)
      .sort((a, b) => a.startMs - b.startMs);
  const merged = [];
  for (const w of parsed) {
    const last = merged[merged.length - 1];
    if (last && w.startMs <= last.endMs) {
      if (w.endMs > last.endMs) {
        last.end = w.end;
        last.endMs = w.endMs;
      }
    } else {
      merged.push({...w});
    }
  }
  return merged.map(({start, end}) => ({start, end}));
}

module.exports = {AGENT_MARKER, deleteCalendarEvent, deleteTaskEvents, findAgentEventIds, getBusyWindows, getForeignBusyWindows, mergeBusyWindows};
